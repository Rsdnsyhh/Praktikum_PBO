class AlatCamping {

    String namaAlat;
    String penyewa;
    int lamaSewa;
    boolean statusKembali;

    AlatCamping(String namaAlat, String penyewa, int lamaSewa) {
        this.namaAlat = namaAlat;
        this.penyewa = penyewa;
        this.lamaSewa = lamaSewa;
        this.statusKembali = false;
    }

}